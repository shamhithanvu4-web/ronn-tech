"""Generate, record and verify reports (SPEC §10)."""
from __future__ import annotations

import json
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.audit import record
from app.errors import AppError, Conflict, NotFound
from app.models import Analysis, Case, ReportRecord
from app.reports.content import analysis_report, content_hash, wrap_with_integrity
from app.reports.pdf import embedded_content_hash, render_analysis_pdf
from app.util import canonical_json, sha256_hex


def _load_done(db: Session, analysis_id: str) -> Analysis:
    a = db.get(Analysis, analysis_id)
    if a is None:
        raise NotFound("Analysis not found.")
    if a.status != "done" or not a.result:
        raise Conflict("The analysis has not finished; reports are available once it is done.", code="analysis_not_done")
    return a


def build_analysis_bundle(db: Session, analysis_id: str, actor: str) -> dict[str, Any]:
    a = _load_done(db, analysis_id)
    case = db.get(Case, a.case_id) if a.case_id else None
    content = analysis_report(a, case, actor)
    return wrap_with_integrity(content, a.result_sha256, (a.result or {}).get("evidence", {}).get("raw_responses", []))


def _record(db: Session, kind: str, object_id: str, fmt: str, file_bytes: bytes, content_digest: str, analysis_sha: str | None, actor: str) -> ReportRecord:
    rec = ReportRecord(
        kind=kind,
        object_id=object_id,
        fmt=fmt,
        file_sha256=sha256_hex(file_bytes),
        content_sha256=content_digest,
        analysis_sha256=analysis_sha,
        generated_by=actor,
    )
    db.add(rec)
    record(db, actor, f"report_generated_{fmt}", kind, object_id, {"file_sha256": rec.file_sha256, "content_sha256": content_digest}, commit=False)
    db.commit()
    return rec


def analysis_pdf(db: Session, analysis_id: str, actor: str) -> tuple[bytes, str]:
    bundle = build_analysis_bundle(db, analysis_id, actor)
    digest = bundle["integrity"]["content_sha256"]
    pdf = render_analysis_pdf(bundle["report"], digest, bundle["integrity"])
    _record(db, "analysis", analysis_id, "pdf", pdf, digest, bundle["integrity"]["analysis_sha256"], actor)
    return pdf, digest


def analysis_json(db: Session, analysis_id: str, actor: str) -> tuple[bytes, str]:
    bundle = build_analysis_bundle(db, analysis_id, actor)
    body = json.dumps(bundle, indent=2, ensure_ascii=False, sort_keys=True).encode("utf-8")
    digest = bundle["integrity"]["content_sha256"]
    _record(db, "analysis", analysis_id, "json", body, digest, bundle["integrity"]["analysis_sha256"], actor)
    return body, digest


def verify_upload(db: Session, data: bytes, filename: str | None, actor: str) -> dict[str, Any]:
    """Recompute hashes of an uploaded report and match them against stored records."""
    if not data:
        raise AppError("The uploaded file is empty.", code="empty_upload")
    file_digest = sha256_hex(data)
    is_pdf = data[:5] == b"%PDF-"
    result: dict[str, Any] = {"filename": filename, "file_sha256": file_digest, "format": "pdf" if is_pdf else "json"}
    by_file = db.execute(select(ReportRecord).where(ReportRecord.file_sha256 == file_digest)).scalars().first()

    if is_pdf:
        embedded = embedded_content_hash(data)
        result["embedded_content_sha256"] = embedded
        if by_file is not None:
            result.update(status="verified", detail="This PDF is byte-for-byte identical to a report generated by this system.")
        elif embedded and db.execute(select(ReportRecord).where(ReportRecord.content_sha256 == embedded)).scalars().first():
            result.update(
                status="tampered",
                detail="The PDF names a report this system generated, but its bytes differ from every stored copy. It has been modified.",
            )
        else:
            result.update(status="unknown", detail="No report generated by this system matches this file.")
    else:
        try:
            doc = json.loads(data.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise AppError("The file is neither a PDF nor a JSON report.", code="unrecognised_report") from exc
        if not isinstance(doc, dict) or "report" not in doc or "integrity" not in doc:
            raise AppError("The JSON is not a report export (missing 'report' or 'integrity').", code="unrecognised_report")
        recomputed = content_hash(doc["report"])
        claimed = (doc.get("integrity") or {}).get("content_sha256")
        result.update(recomputed_content_sha256=recomputed, claimed_content_sha256=claimed)
        known = db.execute(select(ReportRecord).where(ReportRecord.content_sha256 == recomputed)).scalars().first()
        claimed_known = db.execute(select(ReportRecord).where(ReportRecord.content_sha256 == claimed)).scalars().first() if claimed else None
        if by_file is not None and recomputed == claimed:
            result.update(status="verified", detail="This JSON export is byte-for-byte identical to a report generated by this system.")
        elif recomputed == claimed and known is not None:
            result.update(
                status="reformatted",
                detail="The report content still hashes to a recorded report, but the file bytes differ from every stored copy "
                "(re-saved or re-formatted). Use the original file as evidence.",
            )
            by_file = known
        elif claimed_known is not None and recomputed != claimed:
            result.update(status="tampered", detail="The report content no longer matches its recorded SHA-256. It has been modified.")
            by_file = claimed_known
        else:
            result.update(status="unknown", detail="No report generated by this system matches this content.")
    result["valid"] = result["status"] == "verified"
    if by_file is not None:
        result["record"] = {
            "kind": by_file.kind,
            "object_id": by_file.object_id,
            "format": by_file.fmt,
            "generated_by": by_file.generated_by,
            "generated_at": by_file.generated_at.isoformat(timespec="seconds") + "Z",
        }
    record(db, actor, "report_verified", "report", result.get("record", {}).get("object_id", ""), {"status": result["status"], "file_sha256": file_digest})
    return result


def analysis_hash_valid(a: Analysis) -> bool:
    return bool(a.result) and sha256_hex(canonical_json(a.result)) == a.result_sha256
