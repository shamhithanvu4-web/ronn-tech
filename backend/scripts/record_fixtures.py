"""Record the demo cases' real API responses for offline replay (SPEC §14).

    cd backend
    python scripts/record_fixtures.py                 # all cases in fixtures/demo_cases.json
    python scripts/record_fixtures.py --case demo-1-eth-direct-deposit
    python scripts/record_fixtures.py --address T... --chain tron --id my-case --title "..."

For each case it runs the full analysis with DATA_MODE=record (every raw response is saved
to fixtures/<chain>/<sha256>.json, API keys stripped), then runs it again with
DATA_MODE=replay and no network to confirm the result is identical, and writes the
measured outcome into fixtures/demo_cases.json and docs/DEMO_CASES.md.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys

import _bootstrap  # noqa: F401
import httpx

from app import config
from app.config import BACKEND_DIR, SEED_CSV
from app.db import init_db, iso, session_scope, utcnow
from app.engine.datasource import ProductionLabels, ProviderDataSource
from app.engine.pipeline import analyse
from app.errors import AppError
from app.labels.store import label_counts, load_seed_csv
from app.providers import base, cache
from app.providers.context import AnalysisContext, use_context

DEMO_PATH = BACKEND_DIR / "fixtures" / "demo_cases.json"
DOC_PATH = BACKEND_DIR.parent / "docs" / "DEMO_CASES.md"


def _mode(mode: str) -> None:
    os.environ["DATA_MODE"] = mode
    config.reset_settings_cache()


def _run(address: str, chain: str | None) -> dict:
    budget = int(config.scoring_config()["traversal"].get("api_call_budget", 600))
    with session_scope() as db:
        with use_context(AnalysisContext(analysis_id=None, api_call_budget=budget)):
            return asyncio.run(analyse(address, ProviderDataSource(), ProductionLabels(db, enable_live=True), chain_hint=chain))


def _summary(r: dict) -> dict:
    nv = r["summary"]["nearest_vasp"]
    return {
        "nearest_vasp": nv["entity_name"] if nv else None,
        "confidence": nv["confidence"] if nv else None,
        "tier": nv["tier"] if nv else None,
        "hops": nv["hops"] if nv else None,
        "via": nv["via"] if nv else None,
        "risk": r["risk"]["level"],
        "typologies": [t["code"] for t in r["typologies"]],
        "breakpoints": [b["bridge"] for b in r["cross_chain"]["breakpoints"]],
        "candidates": [(c["entity_name"], c["confidence"]) for c in r["candidates"][:3]],
        "partial": r["summary"]["partial"],
    }


def record_case(case: dict) -> dict:
    _mode("record")
    recorded = _run(case["address"], case.get("chain"))
    cache.clear()
    _mode("replay")
    saved = base.HTTP_TRANSPORT

    def offline(request):
        raise RuntimeError(f"network used in replay: {request.url}")

    base.HTTP_TRANSPORT = httpx.MockTransport(offline)
    try:
        replayed = _run(case["address"], case.get("chain"))
    finally:
        base.HTTP_TRANSPORT = saved
    a, b = _summary(recorded), _summary(replayed)
    return {"recorded_at": iso(utcnow()), "expected": b, "replay_matches_record": a == b, "raw_responses": len(replayed["evidence"]["raw_responses"])}


def write_doc(cases: list[dict]) -> None:
    lines = [
        "# Demo cases",
        "",
        "Generated by `scripts/build_ground_truth.py` (real addresses from provider data) and recorded by",
        "`scripts/record_fixtures.py`. With `DATA_MODE=replay` every case below reproduces offline.",
        "",
        "| # | Case | Chain | Wallet | Expected result (measured) | Replay = record |",
        "|---|---|---|---|---|---|",
    ]
    for i, c in enumerate(cases, 1):
        e = (c.get("recording") or {}).get("expected")
        if e is None:
            result = "not recorded yet"
        elif e["nearest_vasp"]:
            result = f"{e['nearest_vasp']} · confidence {e['confidence']:.0f} ({e['tier']}) · {e['hops']} hop(s) · via {e['via']} · risk {e['risk']}"
        else:
            extra = f" · breakpoint {', '.join(e['breakpoints'])}" if e["breakpoints"] else ""
            result = f"No VASP at confidence >= 50 · risk {e['risk']}{extra}" + (f" · typologies {', '.join(e['typologies'])}" if e["typologies"] else "")
        ok = (c.get("recording") or {}).get("replay_matches_record")
        lines.append(f"| {i} | {c['title']} | {c['chain']} | `{c['address']}` | {result} | {'yes' if ok else 'no' if ok is False else '—'} |")
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--case", action="append", default=[], help="only these case ids")
    p.add_argument("--address")
    p.add_argument("--chain")
    p.add_argument("--id")
    p.add_argument("--title", default="Additional recorded case")
    args = p.parse_args(argv)

    if not config.get_settings().ETHERSCAN_API_KEY:
        print("Note: ETHERSCAN_API_KEY is not set; EVM cases cannot be recorded.", file=sys.stderr)
    init_db()
    with session_scope() as db:
        if not label_counts(db):
            load_seed_csv(db, SEED_CSV)
    doc = json.loads(DEMO_PATH.read_text(encoding="utf-8")) if DEMO_PATH.exists() else {"cases": []}
    if args.address:
        doc["cases"].append({"id": args.id or f"extra-{args.address[-8:]}", "title": args.title, "chain": args.chain, "address": args.address, "use_in_sahyog_demo": False})
    if not doc["cases"]:
        print(f"No cases: run scripts/build_ground_truth.py first (it writes {DEMO_PATH}).", file=sys.stderr)
        return 2
    failures = 0
    for case in doc["cases"]:
        if args.case and case["id"] not in args.case:
            continue
        print(f"recording {case['id']} ({case['chain']} {case['address']}) …", flush=True)
        try:
            case["recording"] = record_case(case)
        except (AppError, RuntimeError) as exc:
            failures += 1
            print(f"  failed: {exc}", file=sys.stderr)
            continue
        e = case["recording"]["expected"]
        print(f"  -> {e['nearest_vasp'] or 'no VASP >= 50'} {e['confidence'] or ''} {e['tier'] or ''}; replay matches: {case['recording']['replay_matches_record']}")
        if not case["recording"]["replay_matches_record"]:
            failures += 1
    DEMO_PATH.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    write_doc(doc["cases"])
    print(f"updated {DEMO_PATH.relative_to(BACKEND_DIR)} and docs/DEMO_CASES.md")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
