"use client";

import { useState } from "react";

import { Addr } from "@/components/ui";
import { api } from "@/lib/api";

const LABELS = {
  verified: "Verified: identical to a report generated by this system",
  tampered: "Failed: the file was modified after it was generated",
  reformatted: "Failed: content matches but the file bytes were changed",
  unknown: "Failed: no matching report was generated by this system",
};

export default function ReportVerify() {
  const [file, setFile] = useState(null);
  const [busy, setBusy] = useState(false);
  const [res, setRes] = useState(null);
  const [error, setError] = useState(null);

  async function verify(e) {
    e.preventDefault();
    if (!file) return;
    setBusy(true);
    setError(null);
    setRes(null);
    try {
      setRes(await api.upload("/reports/verify", file));
    } catch (err) {
      setError(err);
    } finally {
      setBusy(false);
    }
  }

  return (
    <form className="stack" onSubmit={verify}>
      <input className="input" type="file" accept=".pdf,.json,application/pdf,application/json" onChange={(e) => setFile(e.target.files?.[0] || null)} />
      <div className="row">
        <button className="btn btn-secondary btn-sm" type="submit" disabled={!file || busy}>
          {busy ? "Checking…" : "Verify hashes"}
        </button>
      </div>
      {error ? <div className="form-error">{error.detail || error.message}</div> : null}
      {res ? (
        <div className={`notice ${res.valid ? "" : "notice-danger"}`} role="status">
          <div className="stack-sm">
            <b>{LABELS[res.status] || res.status}</b>
            <span>{res.detail}</span>
            <span className="small">
              File SHA-256 <Addr value={res.file_sha256} head={12} tail={6} />
            </span>
            {res.record ? (
              <span className="small">
                Report for {res.record.kind} <span className="mono">{res.record.object_id}</span> generated by {res.record.generated_by}
              </span>
            ) : null}
          </div>
        </div>
      ) : null}
    </form>
  );
}
